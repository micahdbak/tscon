// Embed GLSL in module-local shader files so consumers can load shaders without fetching files.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

type Shader = readonly [name: string, kind: "vert" | "frag"];

const SHADERS_DIR = new URL("../shaders/", import.meta.url);

async function gen(name: string, kind: "vert" | "frag"): Promise<string> {
	const src = await readFile(new URL(`${name}.${kind}`, SHADERS_DIR), "utf8");

	return `export const ${name}_${kind} = \`\\\n${src}\`;`;
}

async function writeShaders(out_path: string, shaders: readonly Shader[]): Promise<void> {
	const out =
		[
			"// generated by `bun run shaders`",
			...(await Promise.all(shaders.map(([name, kind]) => gen(name, kind)))),
		].join("\n\n") + "\n";

	const out_file = new URL(out_path, import.meta.url);
	await writeFile(out_file, out);
	console.log(`Wrote ${fileURLToPath(out_file)}`);
}

await writeShaders("../src/renderer/shaders.ts", [
	["glyph", "frag"],
	["renderer", "vert"],
	["renderer", "frag"],
]);
await writeShaders("../src/terminal/shaders.ts", [
	["glyph", "frag"],
	["terminal", "vert"],
	["terminal", "frag"],
]);
